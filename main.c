/**
Составить программу нахождения заданного экстремального элемента
или его порядкового номера при заданном одномерном массиве A из n
элементов (или массивах A и C по n элементов в каждом). Помните, возможен
случай, когда ответ не единственный.

24. Определить наибольшую из абсолютных величин произведений Ai * Cn-i+1.
*/

#include <stdio.h>
#include <malloc.h>
#include <locale.h>
#include <math.h>


int main()
{
    setlocale(0, "");
    setlocale(LC_NUMERIC, "C");

    printf("\n--------------------------------------------------------------------------------\n");
    int n;
    do{
        printf("\nВведите количество элементов n: ");
        scanf("%d", &n);
        if (n <= 0 || n >= 100){
            printf("\n================================================================================\n\t\t");
            printf("Ошибка: нарушен диапазон входных данных\n");
            printf("================================================================================\n");
        }
    }while (n <= 0 || n >= 100);

    printf("\n--------------------------------------------------------------------------------\n");

    double *A;
    A = (double*)malloc((n+1) * sizeof(double));
    printf("\nВведите элементы массива A:\n");
    for (int i = 1; i <= n; i++){
        printf("\nA[%d]: ", i);
        scanf("%lf", &A[i]);
    }

    printf("\n--------------------------------------------------------------------------------\n");

    double *C;
    C = (double*)malloc((n+1) * sizeof(double));
    printf("\nВведите элементы массива C:\n");
    for (int i = 1; i <= n; i++){
        printf("\nC[%d]: ", i);
        scanf("%lf", &C[i]);
    }

    printf("\n--------------------------------------------------------------------------------\n");

    printf("\nВведeнo массив A: [ %g", A[1]);
    for (int i = 2; i <= n; i++){
        printf("; %g", A[i]);
    }
    printf(" ]\n");

    printf("\nВведeнo массив C: [ %g", C[1]);
    for (int i = 2; i <= n; i++){
        printf("; %g", C[i]);
    }
    printf(" ]\n");

    double max = fabs(A[1] * C[n]);
    for (int i = 1; i <= n; i++){
        if (fabs(A[i] * C[n-i+1]) > max){
            max = fabs(A[i] * C[n-i+1]);
        }
    }

    printf("\n================================================================================\n\n\t\t");

    printf("Результат\n\nНаибольшая абсолютная величина произведения A[i]*C[n-i+1]: %g", max);

    printf("\n\n================================================================================\n");

    free(A);
    free(C);

    return 0;
}

